// Command orgnetgen regenerates internal/capture/orgnets.json from the
// vendors' published range files. It reads local files only (download them on
// a connected machine first; the competition network is offline):
//
//	orgnetgen -azure ServiceTags_Public_*.json -aws ip-ranges.json \
//	          -list digitalocean=cloud:do.txt -list linode=cloud:linode.txt > orgnets.json
//
// -azure takes Microsoft's Azure IP Ranges and Service Tags JSON; Microsoft 365
// ranges (endpoints.office.com JSON, -m365) are merged under the same org.
// -aws takes ip-ranges.json. -list org=cloud:file or org=net:file reads a
// plain list of CIDRs, one per line. Prefixes are de-duplicated and sorted.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/netip"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/PurdueBlueTeam/phylax/internal/capture"
)

type multi []string

func (m *multi) String() string     { return strings.Join(*m, ",") }
func (m *multi) Set(s string) error { *m = append(*m, s); return nil }

func main() {
	azure := flag.String("azure", "", "Azure Service Tags JSON")
	m365 := flag.String("m365", "", "Microsoft 365 endpoints JSON")
	aws := flag.String("aws", "", "AWS ip-ranges.json")
	var lists multi
	flag.Var(&lists, "list", "org=cloud:file or org=net:file")
	flag.Parse()
	if err := run(os.Stdout, *azure, *m365, *aws, lists); err != nil {
		fmt.Fprintln(os.Stderr, "orgnetgen:", err)
		os.Exit(1)
	}
}

type acc struct {
	cloud bool
	set   map[string]bool
}

func run(out io.Writer, azure, m365, aws string, lists []string) error {
	orgs := map[string]*acc{}
	add := func(org string, cloud bool, cidr string) error {
		p, err := netip.ParsePrefix(cidr)
		if err != nil {
			return fmt.Errorf("%s: bad prefix %q", org, cidr)
		}
		a := orgs[org]
		if a == nil {
			a = &acc{cloud: cloud, set: map[string]bool{}}
			orgs[org] = a
		}
		a.set[p.Masked().String()] = true
		return nil
	}
	var srcs []string
	if azure != "" {
		var d struct {
			Values []struct {
				Properties struct {
					AddressPrefixes []string `json:"addressPrefixes"`
				} `json:"properties"`
			} `json:"values"`
		}
		if err := readJSON(azure, &d); err != nil {
			return err
		}
		for _, v := range d.Values {
			for _, c := range v.Properties.AddressPrefixes {
				if err := add("microsoft", false, c); err != nil {
					return err
				}
			}
		}
		srcs = append(srcs, "azure:"+azure)
	}
	if m365 != "" {
		var d []struct {
			IPs []string `json:"ips"`
		}
		if err := readJSON(m365, &d); err != nil {
			return err
		}
		for _, e := range d {
			for _, c := range e.IPs {
				if err := add("microsoft", false, c); err != nil {
					return err
				}
			}
		}
		srcs = append(srcs, "m365:"+m365)
	}
	if aws != "" {
		var d struct {
			Prefixes []struct {
				IPPrefix string `json:"ip_prefix"`
			} `json:"prefixes"`
			V6 []struct {
				IPv6Prefix string `json:"ipv6_prefix"`
			} `json:"ipv6_prefixes"`
		}
		if err := readJSON(aws, &d); err != nil {
			return err
		}
		for _, p := range d.Prefixes {
			if err := add("aws", true, p.IPPrefix); err != nil {
				return err
			}
		}
		for _, p := range d.V6 {
			if err := add("aws", true, p.IPv6Prefix); err != nil {
				return err
			}
		}
		srcs = append(srcs, "aws:"+aws)
	}
	for _, l := range lists {
		org, rest, ok := strings.Cut(l, "=")
		kind, file, ok2 := strings.Cut(rest, ":")
		if !ok || !ok2 || (kind != "cloud" && kind != "net") {
			return fmt.Errorf("bad -list %q", l)
		}
		fh, err := os.Open(file)
		if err != nil {
			return err
		}
		sc := bufio.NewScanner(fh)
		for sc.Scan() {
			if t := strings.TrimSpace(sc.Text()); t != "" && !strings.HasPrefix(t, "#") {
				if err := add(org, kind == "cloud", t); err != nil {
					fh.Close()
					return err
				}
			}
		}
		fh.Close()
		srcs = append(srcs, "list:"+file)
	}
	if len(orgs) == 0 {
		return fmt.Errorf("no input")
	}
	f := capture.OrgNetFile{Comment: "Generated by cmd/orgnetgen; do not edit by hand.", Generated: time.Now().UTC().Format("2006-01-02"), Sources: srcs}
	for org, a := range orgs {
		n := struct {
			Org   string   `json:"org"`
			Cloud bool     `json:"cloud,omitempty"`
			CIDRs []string `json:"cidrs"`
		}{Org: org, Cloud: a.cloud}
		for c := range a.set {
			n.CIDRs = append(n.CIDRs, c)
		}
		sort.Strings(n.CIDRs)
		f.Nets = append(f.Nets, n)
	}
	return capture.WriteOrgNets(out, f)
}

func readJSON(path string, v any) error {
	fh, err := os.Open(path)
	if err != nil {
		return err
	}
	defer fh.Close()
	return json.NewDecoder(fh).Decode(v)
}
