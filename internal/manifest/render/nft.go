package render

import (
	"fmt"
	"strings"

	"github.com/PurdueBlueTeam/phylax/internal/manifest"
)

// Tables written by the renderer. The management table is separate so restore
// and drift detection can treat it on its own (design: "Rule hygiene").
const (
	TableMgmt = "phylax_mgmt"
	TableMain = "phylax"
	TableNAT  = "phylax_nat"

	// MgmtMark is the conntrack mark bit set on management flows. The main
	// table accepts any flow carrying it, so a flow admitted by the
	// management table is not re-judged by the service table.
	MgmtMark = "0x7068"
)

// NFTables renders the ruleset for a Linux host as nft script text suitable
// for `nft -f` (and `nft -c -f`). Each table is declared, deleted and
// redefined, so loading the script replaces our tables atomically and
// touches nothing else. The text is deterministic.
func NFTables(hp *HostPolicy) (string, error) {
	if hp.Family == "windows" {
		return "", fmt.Errorf("render: host %s is Windows; use WindowsRules", hp.Host)
	}
	var w strings.Builder
	fmt.Fprintf(&w, "# Generated by phylax from the manifest for host %s. Do not edit.\n", hp.Host)
	fmt.Fprintf(&w, "# default: input %s, output %s", hp.DefaultIn, hp.DefaultOut)
	if hp.Workstation {
		w.WriteString(" (workstation: not covered by server egress rules)")
	}
	w.WriteString("\n\n")

	// Management table: marks management flows, never drops.
	fmt.Fprintf(&w, "table inet %s\ndelete table inet %s\ntable inet %s {\n", TableMgmt, TableMgmt, TableMgmt)
	for _, d := range []Direction{In, Out} {
		hook := map[Direction]string{In: "input", Out: "output"}[d]
		fmt.Fprintf(&w, "\tchain %s {\n\t\ttype filter hook %s priority -10; policy accept;\n", hook, hook)
		for _, r := range hp.Rules {
			if r.Group != GroupMgmt || r.Dir != d {
				continue
			}
			for _, line := range ruleLines(r, true) {
				fmt.Fprintf(&w, "\t\t%s\n", line)
			}
		}
		w.WriteString("\t}\n")
	}
	w.WriteString("}\n\n")

	// Main table.
	fmt.Fprintf(&w, "table inet %s\ndelete table inet %s\ntable inet %s {\n", TableMain, TableMain, TableMain)
	for _, d := range []Direction{In, Out} {
		hook := map[Direction]string{In: "input", Out: "output"}[d]
		def := hp.DefaultIn
		if d == Out {
			def = hp.DefaultOut
		}
		fmt.Fprintf(&w, "\tchain %s {\n\t\ttype filter hook %s priority 0; policy %s;\n", hook, hook, def)
		loIf := map[Direction]string{In: "iif lo", Out: "oif lo"}[d]
		fmt.Fprintf(&w, "\t\t%s accept comment \"loopback\"\n", loIf)
		w.WriteString("\t\tct state invalid drop\n")
		w.WriteString("\t\tct state established,related accept comment \"established and related\"\n")
		fmt.Fprintf(&w, "\t\tct mark & %s == %s accept comment \"management flows (table %s)\"\n", MgmtMark, MgmtMark, TableMgmt)
		for _, r := range hp.Rules {
			if r.Dir != d || r.Group == GroupMgmt {
				continue
			}
			if r.Kind == KindLoopback || r.Kind == KindEstablished {
				continue // emitted above
			}
			for _, line := range ruleLines(r, false) {
				fmt.Fprintf(&w, "\t\t%s\n", line)
			}
		}
		if d == Out && hp.DenyLogGroup != 0 && hp.DefaultOut == Drop {
			fmt.Fprintf(&w, "\t\tlimit rate 100/second burst 200 packets log group %d prefix \"phylax-egress-deny: \" comment \"denied egress; the policy then drops\"\n", hp.DenyLogGroup)
		}
		w.WriteString("\t}\n")
	}
	w.WriteString("}\n")

	// Sinkhole: redirect denied outbound TCP to the loopback catcher. Lives in
	// a nat chain, never in the filter chains.
	if hp.SinkholePort != 0 && hp.DefaultOut == Drop {
		fmt.Fprintf(&w, "\ntable inet %s\ndelete table inet %s\ntable inet %s {\n", TableNAT, TableNAT, TableNAT)
		w.WriteString("\tchain sinkhole {\n\t\ttype nat hook output priority -100; policy accept;\n")
		w.WriteString("\t\toif lo return\n\t\tct state != new return\n")
		for _, r := range hp.Rules {
			// Everything that is allowed out (or deliberately blocked for the canary) must not be redirected.
			if r.Dir != Out || r.Proto != "tcp" {
				continue
			}
			if r.Group == GroupMgmt || r.Group == GroupDependency || r.Group == GroupEgress || r.Group == GroupCanary || r.Group == GroupDomain {
				rr := r
				rr.Action, rr.Log = Accept, false
				for _, line := range ruleLines(rr, false) {
					fmt.Fprintf(&w, "\t\t%s\n", strings.Replace(line, " accept", " return", 1))
				}
			}
		}
		fmt.Fprintf(&w, "\t\tmeta l4proto tcp redirect to :%d comment \"sinkhole: record what the implant would have said\"\n", hp.SinkholePort)
		w.WriteString("\t}\n}\n")
	}
	return w.String(), nil
}

// ruleLines renders one rule as nft statements (v4 and v6 peers become
// separate lines). mark adds the management conntrack mark.
func ruleLines(r Rule, mark bool) []string {
	var matches []string
	dir := r.Dir
	switch r.Proto {
	case "icmp", "icmpv6":
		l4 := map[string]string{"icmp": "icmp", "icmpv6": "ipv6-icmp"}[r.Proto]
		return []string{fmt.Sprintf("meta l4proto %s %s%s", l4, verdict(r, mark), comment(r))}
	case "tcp", "udp":
		matches = append(matches, ports(r.Proto, dir, r)...)
	}
	suffix := verdict(r, mark) + comment(r)
	if mark {
		matches = append(matches, "ct state new")
	}
	var v4, v6 []string
	for _, p := range r.Peers {
		if p.Addr().Is4() {
			v4 = append(v4, p.String())
		} else {
			v6 = append(v6, p.String())
		}
	}
	addrKw := "daddr"
	if dir == In {
		addrKw = "saddr"
	}
	build := func(addrMatch string) string {
		parts := []string{}
		if addrMatch != "" {
			parts = append(parts, addrMatch)
		}
		parts = append(parts, matches...)
		parts = append(parts, suffix)
		return strings.Join(parts, " ")
	}
	if len(r.Peers) == 0 {
		return []string{build("")}
	}
	var lines []string
	if len(v4) > 0 {
		lines = append(lines, build("ip "+addrKw+" "+set(v4)))
	}
	if len(v6) > 0 {
		lines = append(lines, build("ip6 "+addrKw+" "+set(v6)))
	}
	return lines
}

// ports renders the port matches. For In rules LocalPorts are destination
// ports and RemotePorts source ports; for Out rules the reverse.
func ports(proto string, dir Direction, r Rule) []string {
	dst, src := portItems(r.LocalPorts, r.LocalRanges), portItems(r.RemotePorts, r.RemoteRanges)
	if dir == Out {
		dst, src = src, dst
	}
	var out []string
	if len(src) > 0 {
		out = append(out, proto+" sport "+portSet(src))
	}
	if len(dst) > 0 {
		out = append(out, proto+" dport "+portSet(dst))
	}
	if len(out) == 0 {
		out = append(out, "meta l4proto "+proto)
	}
	return out
}

// portItems lists single ports then ranges ("49152-65535" is nft's range syntax).
func portItems(p []uint16, rs []manifest.PortRange) []string {
	var s []string
	for _, v := range p {
		s = append(s, fmt.Sprint(v))
	}
	for _, r := range rs {
		s = append(s, r.String())
	}
	return s
}

func portSet(items []string) string { return set(items) }

func set(items []string) string {
	if len(items) == 1 {
		return items[0]
	}
	return "{ " + strings.Join(items, ", ") + " }"
}

func verdict(r Rule, mark bool) string {
	var parts []string
	if mark {
		parts = append(parts, "ct mark set ct mark | "+MgmtMark)
	}
	if r.Log {
		parts = append(parts, fmt.Sprintf(`limit rate 20/second burst 40 packets log group %d prefix "phylax-canary: "`, r.LogGroup))
	}
	parts = append(parts, string(r.Action))
	return strings.Join(parts, " ")
}

const maxNFTComment = 120

func comment(r Rule) string {
	if r.Comment == "" {
		return ""
	}
	c := strings.Map(func(ch rune) rune {
		if ch == '"' || ch == '\\' || ch == '\n' {
			return '\''
		}
		return ch
	}, r.Comment)
	if len(c) > maxNFTComment {
		c = c[:maxNFTComment-3] + "..." // nft rejects comments over 128 characters
	}
	return fmt.Sprintf(" comment \"%s\"", c)
}
